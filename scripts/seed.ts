import type { PresetFile } from '../shared/types';

const EMOTE_ID = /^[0-9A-Z]{26}$/;

function assertEmoteId(id: string): void {
  if (!EMOTE_ID.test(id)) throw new Error(`Not a 7TV emote ID: ${JSON.stringify(id)}`);
}

/**
 * SQL that seeds the mappings table from the preset files. Safe to re-run:
 * existing rows are left alone, so mappings changed through review survive.
 */
export function buildSeedSql(presets: PresetFile[]): string {
  const statements = presets.map(({ season, mappings }) => {
    const byOriginal = new Map<string, string>();
    for (const { originalId, replacementId } of mappings) {
      assertEmoteId(originalId);
      assertEmoteId(replacementId);
      if (originalId !== replacementId) byOriginal.set(originalId, replacementId);
    }
    const rows = [...byOriginal].map(
      ([original, replacement]) =>
        `  ('seed_${season}_${original}', '${season}', '${original}', '${replacement}', 'seed')`,
    );
    if (rows.length === 0) return `-- ${season}: 0 mappings`;
    return [
      `-- ${season}: ${rows.length} mappings`,
      'INSERT INTO mappings (id, season, original_id, replacement_id, source) VALUES',
      rows.join(',\n'),
      'ON CONFLICT (season, original_id) DO NOTHING;',
    ].join('\n');
  });
  return ['-- Generated by `npm run seed` from data/presets/*.json. Do not edit by hand.', ...statements].join(
    '\n\n',
  ) + '\n';
}
